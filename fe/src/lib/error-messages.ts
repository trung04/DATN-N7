export function localizedErrorMessage(detail: unknown, code?: string, status?: number): string {
  const text = typeof detail === 'string' ? detail.trim() : ''
  if (/[ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđƠơƯưẠ-ỹ]/u.test(text)) {
    return text.replace(/\bbooking\b/gi, word => word === 'Booking' ? 'Đơn đặt phòng' : 'đơn đặt phòng')
  }
  const capacity = /^Maximum adults cannot exceed this room type's largest room capacity \((\d+)\)\.$/.exec(text)
  if (capacity) return `Số người lớn tối đa của loại phòng này là ${capacity[1]}.`

  const english = text.toLowerCase()
  if (Object.hasOwn(messagesByDetail, english)) return messagesByDetail[english]!
  if (code && Object.hasOwn(messagesByCode, code)) return messagesByCode[code]!
  return messagesByStatus[status ?? -1] ?? 'Đã xảy ra lỗi. Vui lòng thử lại.'
}
